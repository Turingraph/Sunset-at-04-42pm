/**
 * Defines a color input for t_gradient argument of the function `paint_gradient_fdf_table`
 * 
 * If the color channel is less than 0, then the color isn't render.
 */
typedef struct t_input_rgba
{
	int	r;
	int	g;
	int	b;
	int	a;
}	t_input_rgba;

typedef enum t_gradient_channel
{
	GRADIENT_RED,
	GRADIENT_GREEN,
	GRADIENT_BLUE,
	GRADIENT_ALPHA,
	GRADIENT_ROW,
	GRADIENT_COL,
	GRADIENT_HEIGHT
}	t_gradient_channel;

/**
 * Defines a color gradient over a selected cell property.
 *
 * cell_channel selects the property used to determine the gradient position.
 * input_start and input_end define the affected range.
 * rgba_start and rgba_end define the colors at the range boundaries.
 */
typedef struct t_gradient
{
	t_input_rgba				rgba_start;
	t_input_rgba				rgba_end;
	t_gradient_channel	cell_channel;
	int					input_start;
	int					input_end;
}	t_gradient;

/**
 * Apply a color or height value to the selected channel of every cell.
 *
 * time/space: O(n) / O(1)
 *
 * @param dst FDF table to modify
 * @param color color or height value to apply. The color value is
 * clamped to the range [0, 255].
 * @param channel selected color or height channel
 * @param is_filtered_cell optional callback used to select which cells
 * are modified. If NULL, every cell is modified.
 */
void		paint_spots_fdf_table(t_fdf_table *dst, int color, t_fdf_channel channel,
				bool (*is_filtered_cell)(const t_fdf_table *dst, size_t index));

/**
 * Apply a color gradient to cells within an input range.
 *
 * time/space: O(n) / O(1)
 *
 * @param dst FDF table to modify
 * @param gradient_input gradient definition
 * @param is_overwrite replace existing colors instead of blending
 */
void		paint_gradient_fdf_table(t_fdf_table *dst,
				t_gradient gradient_input, bool is_overwrite);

/**
 * Paint a table FDF channel using the value of each cell from
 * the origin in the complex plane, as |z.x + z.im|.
 * If aura is not NULL, its output will be utilized instead
 * of the default complex-plane distance.
 * 
 * time/space: O(n) + O(aura) / O(1)
 * 
 * @param dst destination FDF table to paint
 * @param channel FDF channel to paint
 * @param aura optional function to calculate the value of each cell
 */
void	paint_aura_fdf_table(t_fdf_table *dst, t_fdf_channel channel,
	int (*aura)(const t_fdf_table *dst, size_t index));

